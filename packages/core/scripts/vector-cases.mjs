export function buildInput() {
  return {
    cron: {
      count: 20,
      cases: [
        ...CRON_EXPRESSIONS.flatMap((cron, i) =>
          CRON_TIME_ZONES.map((timeZone) => ({
            id: `c${i}-${timeZone}`,
            cron,
            timeZone,
            from: CRON_FROM,
          })),
        ),
        ...INVALID_EXPRESSIONS.map((cron, i) => ({
          id: `bad${i}`,
          cron,
          timeZone: 'UTC',
          from: CRON_FROM[0],
        })),
      ],
    },
    cronTriggers: CRON_TRIGGERS,
    simpleTriggers: SIMPLE_TRIGGERS,
    timeZones: TIME_ZONE_IDS.map((id) => ({ id, at: TIME_ZONE_AT })),
    allTimeZonesAt: TIME_ZONE_AT,
    properties: PROPERTIES.map(([id, text]) => ({ id, text })),
  };
}
